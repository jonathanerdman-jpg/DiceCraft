export function pathOf(grid) {
  const parts = [];
  grid.forEach((row, y) => {
    let x = 0;
    while (x < row.length) {
      if (row[x] !== '#') { x++; continue; }
      let end = x;
      while (end < row.length && row[end] === '#') end++;
      parts.push(`M${x * 2} ${y * 2}h${(end - x) * 2}v2h-${(end - x) * 2}z`);
      x = end;
    }
  });
  return parts.join('');
}

